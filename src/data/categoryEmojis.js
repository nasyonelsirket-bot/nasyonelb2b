function normalize(value) {
  return String(value || '').trim().toLocaleLowerCase('tr');
}

export function filterEmojis(query) {
  const q = normalize(query);
  if (!q) return CATEGORY_EMOJIS;
  return CATEGORY_EMOJIS.filter(
    (item) =>
      item.emoji.includes(q) ||
      item.keywords.some((k) => k.includes(q) || q.includes(k)),
  );
}

export function suggestEmojiForName(name) {
  const q = normalize(name);
  if (!q) return '📦';
  const scored = CATEGORY_EMOJIS.map((item) => {
    let score = 0;
    for (const k of item.keywords) {
      if (k === q) score += 10;
      else if (q.includes(k) || k.includes(q)) score += 5;
      else if (q.split(/\s+/).some((w) => w.length > 2 && (k.includes(w) || w.includes(k)))) score += 2;
    }
    return { emoji: item.emoji, score };
  }).filter((x) => x.score > 0);

  scored.sort((a, b) => b.score - a.score);
  return scored[0]?.emoji || '📦';
}
